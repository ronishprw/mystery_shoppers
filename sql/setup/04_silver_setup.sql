-- 04_silver_setup.sql
-- One-time setup for the silver layer. Run in a Snowflake worksheet as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS METRO_SILVER_DB;
CREATE SCHEMA IF NOT EXISTS METRO_SILVER_DB.MYSTERY_SHOPPER;

GRANT USAGE ON DATABASE METRO_SILVER_DB TO ROLE DATA_ENGINEER;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA METRO_SILVER_DB.MYSTERY_SHOPPER TO ROLE DATA_ENGINEER;
