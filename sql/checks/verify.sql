USE ROLE DATA_ENGINEER;
USE WAREHOUSE WH_DATA_ENGINEER;
USE SCHEMA METRO_BRONZE_DB.MYSTERY_SHOPPER;

-- 1. Files sitting in the stage
LIST @sftp_stage;

-- 2. What happened to each file (newest first)
SELECT FILE_NAME, TARGET_TABLE, STATUS, ROWS_READ, ROWS_LOADED, ROWS_REJECTED, MESSAGE, PROCESSED_AT
FROM FILE_AUDIT
ORDER BY PROCESSED_AT DESC;

-- 3. Row counts: bronze (good rows) and rejects (bad rows)
SELECT 'categories' AS tbl, COUNT(*) AS bronze_rows FROM MYSTERY_SHOPPING_CATEGORIES
UNION ALL SELECT 'jobs', COUNT(*) FROM MYSTERY_SHOPPING_JOBS
UNION ALL SELECT 'questions', COUNT(*) FROM MYSTERY_SHOPPING_QUESTIONS;

SELECT 'categories' AS tbl, COUNT(*) AS reject_rows FROM MYSTERY_SHOPPING_CATEGORIES_REJECTS
UNION ALL SELECT 'jobs', COUNT(*) FROM MYSTERY_SHOPPING_JOBS_REJECTS
UNION ALL SELECT 'questions', COUNT(*) FROM MYSTERY_SHOPPING_QUESTIONS_REJECTS;

-- 4. Why rows were rejected
SELECT 'jobs' AS tbl, DQ_FILE_NAME, DQ_REASON, COUNT(*) AS n
FROM MYSTERY_SHOPPING_JOBS_REJECTS GROUP BY 1, 2, 3 ORDER BY n DESC;

